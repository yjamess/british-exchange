import Link from "next/link";
import { SeriesChart } from "@/components/SeriesChart";
import { SourcePanel } from "@/components/SourcePanel";
import { fetchIndicator, fetchObservations } from "@/lib/api";
import styles from "../page.module.css";

export const dynamic = "force-dynamic";

/** Show gas generation as a simple single-series proof (aggregates already excluded). */
const FUEL = "Gas";

export default async function EnergyPage() {
  let meta;
  let observations;
  let error: string | null = null;

  try {
    [meta, observations] = await Promise.all([
      fetchIndicator("electricity-generation-by-source"),
      fetchObservations("electricity-generation-by-source", {
        fuel: FUEL,
        include_aggregates: "false",
      }),
    ]);
  } catch (err) {
    error = err instanceof Error ? err.message : "Unknown API error";
  }

  const chart = observations?.chart ?? meta?.chart;

  return (
    <main className={styles.shell}>
      <p className={styles.brand}>Britain Exchange</p>
      <nav className={styles.nav} aria-label="Indicators">
        <Link href="/">Real GDP</Link>
        <Link href="/energy" aria-current="page">
          Electricity by fuel
        </Link>
      </nav>

      <header className={styles.hero}>
        <p className={styles.kicker}>First proof · Energy</p>
        <h1 className={styles.title}>UK electricity from {FUEL} (quarterly)</h1>
        <p className={styles.lede}>
          What you are seeing: DESNZ Energy Trends <strong>ET 5.1</strong> —
          electricity generated by {FUEL}, All generating companies, United
          Kingdom, in TWh. Filtered with typed dimension{" "}
          <code>fuel={FUEL}</code> via{" "}
          <code>/indicators/electricity-generation-by-source/observations?fuel={FUEL}</code>
          . Aggregate “Total*” fuels are not included.
        </p>
      </header>

      {error || !meta || !observations ? (
        <div className={styles.error} role="alert">
          <strong>API unavailable.</strong> Start the FastAPI server, then refresh.
          <code>uv run uvicorn britain_exchange.api:app --reload</code>
          {error ? <code>{error}</code> : null}
        </div>
      ) : (
        <>
          <section className={styles.chartCard} aria-label={`${FUEL} generation chart`}>
            <SeriesChart
              rows={observations.observations}
              unit={meta.unit}
              seriesLabel={`Electricity generated — ${FUEL}`}
              seriesId="ET 5.1"
              geography={meta.geography}
              frequency={meta.frequency}
              chart={chart}
              sourceNote={`Filtered on dimensions.fuel=${FUEL}. API excluded ${observations.excluded_aggregate_rows} aggregate rows before this filter.`}
            />
          </section>
          <SourcePanel
            meta={meta}
            chart={chart}
            observationCount={observations.count}
            note={`Typed filter dimensions.fuel=${FUEL}. Aggregate fuel totals stay out of default charts.`}
          />
        </>
      )}
    </main>
  );
}
