export function resolveEnergyConnectionHref(
  conn: Connection,
  selection: ConnectionSelection = {},
  current?: URLSearchParams | string | null,
  arrival?: ArrivalContext | null,
): string | null {
  return resolveConnectionHref(conn, selection, current, arrival);
}

/**
 * Follow-this-fuel: prefer a fuel-specific contextual edge; otherwise the
 * direct Generation Data hop.
 */
export function followFuelConnection(
  fuelId: string,
  selection: ConnectionSelection = {},
  current?: URLSearchParams | string | null,
  arrival?: ArrivalContext | null,
): { connection: Connection; href: string | null } | null {
  const merged = { fuel: fuelId, ...selection };
  const origin = { sector: "energy" as const, domain: "generation" };
  const matches = connectionsFor(origin, merged, REGISTRY).filter(
    (c) => c.from.selectionKey === "fuel",
  );
  const ranked = [...matches].sort((a, b) => {
    const score = (c: Connection) =>
      c.id === "gen.fuel→gen.data" ? 2 : c.kind === "contextual" ? 0 : 1;
    return score(a) - score(b);
  });
  const connection = ranked[0];
  if (!connection) return null;
  return {
    connection,
    href: resolveConnectionHref(connection, merged, current, arrival),
  };
}

export function stationNationalGenerationHref(
  fuel: string,
  year: number,
  arrival?: ArrivalContext | null,
): string | null {
  const conn = energyConnectionById("gen.station→gen.data");
  if (!conn) return null;
  return resolveConnectionHref(conn, { fuel, year }, null, arrival);
}

