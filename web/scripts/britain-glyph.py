"""Build the UK outline used by the footer glyph (web/src/brand/motion/glyphs.britain.ts).

Dissolves the ONS local-authority boundaries (Dec 2025, ultra-generalised, OGL v3.0)
already archived under data/regions/housing-boundaries into one outline, projects it
(equirectangular, x scaled by cos 54.5°), drops islands too small to read at a 5px dot
pitch, simplifies, and writes a compact SVG path in a 0–100 tall box.

    uv run python web/scripts/britain-glyph.py
"""

from __future__ import annotations

import json
import math
from pathlib import Path

from shapely.geometry import MultiPolygon, Polygon, shape
from shapely.ops import unary_union

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "data/regions/housing-boundaries/curated/boundaries.geojson"
OUT = ROOT / "web/src/brand/motion/glyphs.britain.ts"

K = math.cos(math.radians(54.5))
MIN_AREA = 0.01  # projected deg²; keeps the larger islands (Skye, Lewis, Orkney, Shetland, Anglesey)
TOLERANCE = 0.035  # projected deg; plenty at a 4–6px dot pitch


def project(poly: Polygon) -> Polygon:
    return Polygon([(x * K, -y) for x, y in poly.exterior.coords])


def main() -> None:
    features = json.loads(SRC.read_text())["features"]
    merged = unary_union([shape(f["geometry"]).buffer(0) for f in features])
    parts = list(merged.geoms) if isinstance(merged, MultiPolygon) else [merged]
    polys = [project(p) for p in parts]
    polys = [p.simplify(TOLERANCE, preserve_topology=True) for p in polys if p.area >= MIN_AREA]
    minx = min(p.bounds[0] for p in polys)
    miny = min(p.bounds[1] for p in polys)
    maxx = max(p.bounds[2] for p in polys)
    maxy = max(p.bounds[3] for p in polys)
    s = 100 / (maxy - miny)
    width = round((maxx - minx) * s, 1)

    def ring(coords) -> str:
        pts = [f"{(x - minx) * s:.1f} {(y - miny) * s:.1f}" for x, y in list(coords)[:-1]]
        return "M" + "L".join(pts) + "Z"

    path = "".join(ring(p.exterior.coords) for p in sorted(polys, key=lambda p: -p.area))
    OUT.write_text(
        "// Generated by web/scripts/britain-glyph.py — do not edit by hand.\n"
        "// Source: ONS Local Authority Districts (December 2025) Boundaries UK BUC, dissolved.\n"
        "// Contains OS data © Crown copyright and database right 2025. Open Government Licence v3.0.\n"
        f"export const BRITAIN = {{ width: {width}, height: 100, d: {json.dumps(path)} }};\n"
    )
    print(f"{len(polys)} rings, {len(path)} chars, {width}×100 → {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
