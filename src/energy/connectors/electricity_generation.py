"""DESNZ Energy Trends ET 5.1 — electricity generation by fuel (TWh).

Approach (beginner-friendly):
1. Prefer the pinned raw XLSX under data/energy/.../raw/ (immutable evidence).
2. Parse only Quarter sheet Table 5.1b, "All generating companies" rows.
3. Emit one Observation per fuel × quarter; fuel goes in notes as fuel=<Label>.
4. Write curated CSV + manifest via the shared Connector.write_hand_off.

Best practices used:
- pathlib.Path for paths (https://docs.python.org/3/library/pathlib.html)
- type hints on public functions (https://docs.python.org/3/library/typing.html)
- Fail loudly on missing sheets / unexpected layout; never invent numbers.
"""

from __future__ import annotations

import calendar
import re
from datetime import datetime, timezone
from pathlib import Path
from typing import Sequence

import openpyxl
from openpyxl.worksheet.worksheet import Worksheet

from britain_exchange.checksum import sha256_file
from britain_exchange.connector import Connector
from britain_exchange.manifest import Manifest, RawEvidence
from britain_exchange.observation import Observation, ObservationStatus
from britain_exchange.paths import ENERGY_DATA

# Orchestrator-binding geography for UK.
UK_GEOGRAPHY_CODE = "K02000001"
UK_GEOGRAPHY_LABEL = "United Kingdom"

PINNED_RAW_RELATIVE = "raw/2026-11-03/ET_5.1_SEP_26.xlsx"
SOURCE_LANDING_URL = (
    "https://www.gov.uk/government/statistics/electricity-section-5-energy-trends"
)
# Asset URL at T03 retrieve time (mutable on GOV.UK — prefer landing page next run).
PINNED_ASSET_URL = (
    "https://assets.publishing.service.gov.uk/media/"
    "6aba6dd9a9c3d267bcccefb0/ET_5.1_SEP_26.xlsx"
)
OFFICIAL_RELEASE_DATE = "2026-09-29"
SOURCE_VERSION = "ET_5.1_SEP_26"

GENERATOR_TYPE_ALL = "All generating companies"
TABLE_5_1B_TITLE = "Table 5.1b: electricity generated by fuel (TWh)"
QUARTER_HEADER_RE = re.compile(
    r"^Quarter\s+([1-4])\s+(\d{4})(?:\s*\[([^\]]+)\])?\s*$",
    re.IGNORECASE,
)
MISSING_MARKERS = {"[x]", "[z]", "..", "…"}


def _quarter_bounds(year: int, quarter: int) -> tuple[str, str]:
    """Return inclusive ISO dates for a calendar quarter.

    Q1=Jan–Mar, Q2=Apr–Jun, Q3=Jul–Sep, Q4=Oct–Dec.
    """
    start_month = 1 + (quarter - 1) * 3
    end_month = start_month + 2
    start = f"{year:04d}-{start_month:02d}-01"
    end_day = calendar.monthrange(year, end_month)[1]
    end = f"{year:04d}-{end_month:02d}-{end_day:02d}"
    return start, end


def _parse_quarter_header(raw: object) -> tuple[str, str, ObservationStatus] | None:
    """Parse 'Quarter 2 2026 [provisional]' → (period_start, period_end, status)."""
    if raw is None:
        return None
    text = str(raw).strip()
    match = QUARTER_HEADER_RE.match(text)
    if not match:
        return None
    quarter = int(match.group(1))
    year = int(match.group(2))
    flag = (match.group(3) or "").strip().lower()
    start, end = _quarter_bounds(year, quarter)
    status: ObservationStatus = "provisional" if "provisional" in flag else "final"
    return start, end, status


def _clean_fuel_label(raw: object) -> str:
    """Exact fuel label from the sheet, trimming Excel trailing spaces only."""
    return str(raw).strip()


def _parse_numeric_cell(
    raw: object,
) -> tuple[float | None, ObservationStatus | None]:
    """Return (value, override_status). override_status is set for missing cells."""
    if raw is None:
        return None, "missing"
    if isinstance(raw, (int, float)):
        return float(raw), None
    text = str(raw).strip()
    if not text or text.lower() in MISSING_MARKERS:
        return None, "missing"
    # Rare: numeric stored as string
    try:
        return float(text.replace(",", "")), None
    except ValueError:
        return None, "missing"


def _find_row_index(ws: Worksheet, needle: str) -> int:
    """1-based row index whose first cell equals needle (substring match)."""
    target = needle.casefold()
    for row in ws.iter_rows(min_row=1, max_row=ws.max_row or 200, max_col=1):
        cell = row[0].value
        if cell is not None and target in str(cell).strip().casefold():
            return row[0].row
    raise ValueError(f"Could not find row containing {needle!r} on sheet {ws.title!r}")


def _load_quarter_sheet(workbook_path: Path) -> Worksheet:
    wb = openpyxl.load_workbook(workbook_path, data_only=True, read_only=False)
    if "Quarter" not in wb.sheetnames:
        wb.close()
        raise ValueError(f"Workbook missing 'Quarter' sheet: {workbook_path}")
    # Keep workbook open via worksheet._parent; caller must close via ws.parent.
    return wb["Quarter"]


def parse_et51_quarter_generation_twh(workbook_path: Path) -> list[Observation]:
    """Parse ET 5.1 Quarter sheet Table 5.1b → All generating companies, TWh."""
    ws = _load_quarter_sheet(workbook_path)
    wb = ws.parent
    try:
        title_row = _find_row_index(ws, TABLE_5_1B_TITLE)
        header_row = title_row + 1
        header_cells = list(ws[header_row])
        periods: list[tuple[int, str, str, ObservationStatus]] = []
        for col_idx, cell in enumerate(header_cells, start=1):
            parsed = _parse_quarter_header(cell.value)
            if parsed is None:
                continue
            period_start, period_end, status = parsed
            periods.append((col_idx, period_start, period_end, status))
        if not periods:
            raise ValueError("No quarter columns found on Table 5.1b header row")

        observations: list[Observation] = []
        # Data starts immediately under the header; stop at next table title.
        row_idx = header_row + 1
        max_row = ws.max_row or row_idx
        while row_idx <= max_row:
            generator = ws.cell(row_idx, 1).value
            fuel_raw = ws.cell(row_idx, 2).value
            first_cell = generator if generator is not None else fuel_raw
            if first_cell is not None and str(first_cell).strip().lower().startswith(
                "table "
            ):
                break
            # Generator type is often blank on continuation rows; track last seen.
            # For All-generating block, column A repeats on each fuel row in this file.
            if generator is None and fuel_raw is None:
                row_idx += 1
                continue
            generator_label = (
                str(generator).strip() if generator is not None else ""
            )
            if generator_label != GENERATOR_TYPE_ALL:
                row_idx += 1
                continue
            if fuel_raw is None:
                row_idx += 1
                continue

            fuel = _clean_fuel_label(fuel_raw)
            for col_idx, period_start, period_end, header_status in periods:
                value, missing_status = _parse_numeric_cell(
                    ws.cell(row_idx, col_idx).value
                )
                status: ObservationStatus = missing_status or header_status
                observations.append(
                    Observation(
                        indicator_id="electricity-generation-by-source",
                        period_start=period_start,
                        period_end=period_end,
                        geography_code=UK_GEOGRAPHY_CODE,
                        geography_label=UK_GEOGRAPHY_LABEL,
                        value=value,
                        unit="TWh",
                        observation_status=status,
                        source_version=SOURCE_VERSION,
                        notes=f"fuel={fuel}",
                    )
                )
            row_idx += 1

        if not observations:
            raise ValueError(
                "No All generating companies rows parsed from Table 5.1b"
            )
        return observations
    finally:
        wb.close()


class ElectricityGenerationConnector(Connector):
    """DESNZ electricity generation by fuel/source — first proof indicator."""

    def __init__(self, data_root: Path | None = None) -> None:
        root = data_root or (ENERGY_DATA / "electricity-generation-by-source")
        super().__init__(root)

    @property
    def indicator_id(self) -> str:
        return "electricity-generation-by-source"

    def build_manifest(self, evidence: Sequence[RawEvidence]) -> Manifest:
        return Manifest(
            indicator_id=self.indicator_id,
            title="Electricity generation by source",
            sector="energy-industry",
            publisher="DESNZ",
            source_url=SOURCE_LANDING_URL,
            series_id="ET 5.1 (Electricity generated by fuel, TWh)",
            geography="UK (K02000001)",
            frequency="quarterly",
            unit="TWh",
            definition=(
                "UK electricity generated by fuel/source (TWh) from Energy Trends "
                "table ET 5.1 Quarter sheet Table 5.1b, All generating companies "
                "(Major Power Producers + other generators). One observation per "
                "fuel × calendar quarter; fuel label in notes as fuel=<Label>."
            ),
            licence="Open Government Licence v3.0",
            agent_owner="energy",
            connector_module="energy.connectors.electricity_generation",
            curated_path="curated/observations.csv",
            update_cadence=(
                "Quarterly — Energy Trends electricity tables, last Thursday of "
                "Mar/Jun/Sep/Dec (data one quarter in arrears)"
            ),
            raw_evidence=list(evidence),
            notion_registry_url="https://app.notion.com/40d65471768581839535dd21683f6238",
            transformations=(
                "Parse Quarter!Table 5.1b (TWh). Keep only rows where Generator "
                "type == 'All generating companies'. Long-format: one CSV row per "
                "fuel × quarter. Strip trailing spaces from fuel labels. Map "
                "[x] → value null + observation_status=missing. Headers containing "
                "[provisional] → observation_status=provisional. Periods are "
                "calendar-quarter ISO dates. Annual sheet not ingested (see README)."
            ),
            caveats=(
                "Prefer TWh 'Electricity generated by fuel' rows, not Mtoe fuel-used. "
                "Bioenergy vs non-biodegradable waste break: Q1 2007 (other) / Q1 2013 (MPP). "
                "Wind includes wave and tidal for other generators / all generators. "
                "Aggregation: fuel=Total wind and fuel=Total all generating companies are "
                "aggregates — never sum them with component fuels. API defaults to "
                "include_aggregates=false. See britain_exchange.aggregation. "
                "GOV.UK asset media URLs change each release; pin checksummed raw snapshots."
            ),
            open_questions=[
                "Optional Annual sheet TWh as a secondary curated file.",
            ],
        )

    def evidence_from_pinned_raw(self) -> RawEvidence:
        """Build RawEvidence for the T03-pinned workbook without re-downloading."""
        relative = PINNED_RAW_RELATIVE
        path = self.data_root / relative
        if not path.is_file():
            raise FileNotFoundError(
                f"Pinned raw workbook missing: {path}. Re-run fetch or restore T03 pin."
            )
        return RawEvidence(
            path=relative,
            retrieved_at=datetime.now(timezone.utc).isoformat(),
            checksum_sha256=sha256_file(path),
            content_type=(
                "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet"
            ),
            official_release_date=OFFICIAL_RELEASE_DATE,
            http_status=None,
            source_url=PINNED_ASSET_URL,
        )

    def transform(self, evidence: Sequence[RawEvidence]) -> list[Observation]:
        if not evidence:
            raise ValueError("transform() requires at least one RawEvidence entry")
        workbook = self.data_root / evidence[0].path
        if not workbook.is_file():
            raise FileNotFoundError(f"Raw workbook not found: {workbook}")
        return parse_et51_quarter_generation_twh(workbook)


def main() -> None:
    """Run T04 hand-off: pinned raw → curated observations + manifest."""
    connector = ElectricityGenerationConnector()
    evidence = connector.evidence_from_pinned_raw()
    observations = connector.transform([evidence])
    manifest_path, curated_path = connector.write_hand_off([evidence], observations)

    fuels = sorted(
        {
            obs.notes.removeprefix("fuel=")
            for obs in observations
            if obs.notes.startswith("fuel=")
        }
    )
    print(f"indicator_id: {connector.indicator_id}")
    print(f"raw: {evidence.path} sha256={evidence.checksum_sha256}")
    print(f"observations: {len(observations)}")
    print(f"fuels ({len(fuels)}): {', '.join(fuels)}")
    print(f"manifest: {manifest_path}")
    print(f"curated: {curated_path}")


if __name__ == "__main__":
    main()
